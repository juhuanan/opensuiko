test "inclusive source guard and asset digest" {
    var opened = try destination.open(std.testing.allocator, data.json, data.ground_json);
    defer opened.deinit();
    try std.testing.expect(opened.roomDescriptorContext("va1_room_0").?.entry_title_hold);
    try std.testing.expect(!opened.roomDescriptorContext("va1_room_1").?.entry_title_hold);
    const route = opened.parsed.value.route;
    for ([_]u8{ 32, 33, 37, 38 }) |x| try std.testing.expect(route.matchesCell(x, 104));
    for ([_]u8{ 0, 31, 39, 255 }) |x| try std.testing.expect(!route.matchesCell(x, 104));
    for ([_]u8{ 0, 103, 105, 255 }) |y| try std.testing.expect(!route.matchesCell(35, y));
    const room0_exit = opened.route(0, 15).?;
    try std.testing.expect(room0_exit.matchesCell(37, 93));
    try std.testing.expect(room0_exit.matchesCell(41, 94));
    try std.testing.expect(!room0_exit.matchesCell(36, 93));
    try std.testing.expect(!room0_exit.matchesCell(37, 95));
    try std.testing.expectEqualStrings("vaa_room_10", room0_exit.destination);
    const room10_exit = opened.route(10, 1).?;
    try std.testing.expect(room10_exit.matchesCell(18, 29));
    try std.testing.expect(room10_exit.matchesCell(28, 30));
    try std.testing.expect(!room10_exit.matchesCell(17, 29));
    try std.testing.expect(!room10_exit.matchesCell(18, 31));
    try std.testing.expectEqualStrings("va1_room_0", room10_exit.destination);
    try std.testing.expectEqual(@as(u16, 808), room10_exit.x);
    try std.testing.expectEqual(@as(u16, 56), room10_exit.y);
    const altered = try std.testing.allocator.dupe(u8, data.json);
    defer std.testing.allocator.free(altered);
    altered[0] ^= 1;
    try std.testing.expectError(error.InvalidDestinationDigest, destination.open(std.testing.allocator, altered, data.ground_json));
    const altered_ground = try std.testing.allocator.alloc(u8, data.ground_json.len + 1);
    defer std.testing.allocator.free(altered_ground);
    @memcpy(altered_ground[0..data.ground_json.len], data.ground_json);
    altered_ground[data.ground_json.len] = ' ';
    try std.testing.expectError(error.InvalidDestinationGroundDigest, destination.open(std.testing.allocator, data.json, altered_ground));
}
