//! Source-qualified, data-driven contracts for the three optional games:
//! dice (VB2), the three-cup COIN game and the KARUTA pair board.
//!
//! This module is a *logical* implementation of the source rules. It owns
//! phases, legal inputs, completion gates and restartable result proposals. It
//! owns no money, no story flag, no receipt ledger and no RNG stream: every
//! result is a proposal that the canonical owner must acknowledge atomically
//! with a matching receipt. Presentation (3D dice pips, cup animation, card
//! drawing) is deliberately outside this module and stays a typed blocker in
//! the report.
//!
//! The rules are parsed from the pinned asset bytes generated by
//! `kit/tools/export_optional_game_contracts.py` from static instruction/data
//! assertions in the overlays. No source RAM address is present here.

const std = @import("std");
const draws_mod = @import("battle_rules");

pub const schema = "suikoden.optional-games.v1";

/// Exact-file SHA-256 of `game/assets/optional_game_contracts.json`.
pub const asset_sha256 = [32]u8{
    0x99, 0x97, 0x54, 0xb0, 0x8c, 0xfa, 0xf0, 0x23,
    0x56, 0x30, 0x9b, 0xa6, 0xc8, 0xff, 0xe0, 0x5c,
    0xcf, 0xda, 0xf1, 0x8e, 0xfd, 0x9d, 0xe9, 0xa7,
    0x64, 0x7a, 0xd0, 0x24, 0x46, 0x2e, 0x1f, 0x05,
};

pub const Draws = draws_mod.Draws;

const rules_mod = @import("optional_game_rules.zig");
const dice_mod = @import("optional_game_dice.zig");
const coin_mod = @import("optional_game_coin.zig");
const karuta_mod = @import("optional_game_karuta.zig");

// ---------------------------------------------------------------------------
// Data
// ---------------------------------------------------------------------------

pub const DiceSpecial = rules_mod.DiceSpecial;
pub const DiceMode = rules_mod.DiceMode;
pub const DiceRules = rules_mod.DiceRules;
pub const CoinRules = rules_mod.CoinRules;
pub const KarutaRound = rules_mod.KarutaRound;
pub const KarutaRules = rules_mod.KarutaRules;

pub const Contracts = struct {
    dice: DiceRules,
    coin: CoinRules,
    karuta: KarutaRules,

    /// Parse and verify the pinned asset bytes. The digest is the exact-file
    /// identity of `game/assets/optional_game_contracts.json`; a regenerated
    /// asset must update it deliberately.
    pub fn parse(allocator: std.mem.Allocator, bytes: []const u8) !Contracts {
        var digest: [32]u8 = undefined;
        std.crypto.hash.sha2.Sha256.hash(bytes, &digest, .{});
        if (!std.mem.eql(u8, &digest, &asset_sha256)) return error.AssetIdentityMismatch;
        const families = try rules_mod.parseFamilies(allocator, bytes, schema);
        return .{
            .dice = families.dice,
            .coin = families.coin,
            .karuta = families.karuta,
        };
    }
};

