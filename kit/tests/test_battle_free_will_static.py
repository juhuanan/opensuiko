"""Check Free Will source bytes and retained witnesses without executing PS1 code.

The fixture is a pre-existing source witness, not regenerated by this test.
The small rules model is derived from manual/11-battle.md and checked against
all retained cases; the separate world trace remains a hash-pinned witness.
"""
from copy import deepcopy
import hashlib
import json
from pathlib import Path
import sys
import unittest

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'kit/tools'))
import maindec

SOURCE_BLOCKS = (
    (0x800EE5B8, 0x800EE7A8, '5dc1a409d4a033d22b708f0a9104337aa773c9dd74a5af3f912ea65478168936'),
    (0x800EEC20, 0x800EEDD0, '31f6218e1decccea11aa98a204888b5563247575daa900cc9b54804095ec9a50'),
    (0x800E9FD0, 0x800EA0AC, '6c6faee3bed6a30b00321cd911c2a8279e0b863594dd36e3313bb9503d42def8'),
)


def commands(case):
    """Apply formation, weapon range and the source rotation stop condition."""
    targets = [i for i, alive in enumerate(case['alive']) if alive]
    result = [None] * len(case['formation'])
    cursor = 0
    for slot, member in enumerate(case['formation']):
        kind = case['ranges'][member]

        def reaches(target):
            return kind == 'long' or (case['enemy_rows'][target] == 'front' and
                                      (kind == 'medium' or slot < 3))

        if case['statuses'][member] != 'healthy' or not any(reaches(t) for t in targets):
            continue
        candidate = cursor + 1
        while True:
            if candidate >= len(targets):
                candidate = 0
            if reaches(targets[candidate]):
                result[member] = targets[candidate]
                break
            candidate += 1
            if candidate == cursor:
                break
        cursor = (cursor + 1) % len(targets)
    return result


class FreeWillStaticTest(unittest.TestCase):
    def test_source_blocks(self):
        image = maindec.body()
        for start, end, expected in SOURCE_BLOCKS:
            with self.subTest(start=hex(start)):
                block = image[start - maindec.MBASE:end - maindec.MBASE]
                self.assertEqual(len(block), end - start)
                self.assertEqual(hashlib.sha256(block).hexdigest(), expected)

    def test_retained_command_witnesses(self):
        path = ROOT / 'game/tests/fixtures/battle_free_will.json'
        raw = path.read_bytes()
        self.assertEqual(hashlib.sha256(raw).hexdigest(),
                         '823717ab1e5f3b6bbd52ff321e3670cfac22a3584a0ddcf1373d517d096df58f')
        cases = json.loads(raw)
        self.assertEqual(len(cases), 55)
        for index, case in enumerate(cases):
            with self.subTest(index=index):
                self.assertEqual(commands(case), case['actions'])

        # Down members prepare a command and consume the cursor; sleep does not.
        first = deepcopy(cases[0])
        first['knocked_out'][0] = True
        self.assertEqual(commands(first), cases[0]['actions'])
        first['statuses'][0] = 'sleep'
        self.assertEqual(commands(first), [None, 1, 0, None, 1, 0])

    def test_retained_world_witness(self):
        raw = (ROOT / 'game/tests/fixtures/world_c_free_will.json').read_bytes()
        self.assertEqual(hashlib.sha256(raw).hexdigest(),
                         'd79dd84360f3b10edb7ddddea10e5b0433535f71a9d5fd202f5d415f42edb556')
        witness = json.loads(raw)
        self.assertEqual(witness['free_will_source_commands'], [1, 0, 1, None, 0, 1])
        self.assertEqual((witness['round_gate'], len(witness['rows']), len(witness['draws'])), (429, 429, 37))


if __name__ == '__main__':
    unittest.main()
